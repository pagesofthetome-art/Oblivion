# ---------------------------------------------------------------- records
def _xcll(ambient=(150, 145, 140), directional=(255, 245, 225), fog=(30, 30, 35)) -> bytes:
    return (bytes([*ambient, 0]) + bytes([*directional, 0]) + bytes([*fog, 0])
            + struct.pack("<ffiiff", 2000.0, 12000.0, 45, 60, 1.0, 20000.0))


def _clas(w: PluginWriter) -> int:
    r = w.record("CLAS", "ForgeTestClass")
    r.add("FULL", zs("Test Subject"))
    major = [SKILL_AV[s] for s in ("Blade", "Block", "Blunt", "HeavyArmor", "Athletics", "Destruction", "Mercantile")]
    r.add("DATA", struct.pack("<2iI7iIIbB2x", 0, 1, 0, *major, 0, 0, 0, 0))
    return r.fid


def _npc(w: PluginWriter, edid: str, d: dict, class_fid: int, pkg_fids: dict, form_fid) -> None:
    r = w.record("NPC_", edid)
    r.add("FULL", zs(d["name"]))
    r.add("MODL", zs(SKELETON))
    flags = 0x02 if d.get("essential") else 0
    r.add("ACBS", struct.pack("<IHHHhHH", flags, 0, 0, d.get("barter_gold", 0), d["level"], 0, 0))
    r.add("RNAM", u32(IMPERIAL_RACE))
    for item, count in d.get("items", []):
        r.add("CNTO", struct.pack("<Ii", form_fid(item), count))
    services = 0
    for s in d.get("services", []):
        services |= SERVICES[s]
    r.add("AIDT", struct.pack("<BBBBIbBH", d["aggression"], d["confidence"], 50, 50, services, -1, 0, 0))
    for p in d.get("packages", []):
        r.add("PKID", u32(pkg_fids[p]))
    r.add("CNAM", u32(class_fid))
    skills = [d.get("skills", 10)] * 21
    if "mercantile" in d:
        skills[SKILLS.index("Mercantile")] = d["mercantile"]
    r.add("DATA", bytes(skills) + struct.pack("<I", d["health"]) + bytes([d.get("attributes", 40)] * 8))


def _package(w: PluginWriter, edid: str, p: dict, ref_fid) -> int:
    r = w.record("PACK", edid)
    r.add("PKDT", struct.pack("<IB3x", p["flags"], PACKAGE_TYPES[p["type"]]))
    ltype, target, radius = p["location"]
    r.add("PLDT", struct.pack("<iIi", LOCATION_TYPES[ltype], ref_fid(target) if target else 0, radius))
    r.add("PSDT", struct.pack("<bbBbi", -1, -1, 0, p["hour"], p["duration"]))
    return r.fid


def build_plugin(lay: dict | None = None) -> tuple[bytes, dict]:
    """Return (plugin bytes, layout with resolved FormIDs). Deterministic."""
    lay = json.loads(json.dumps(lay or layout()))
    w = PluginWriter(MASTERS, author="TES4Forge playtest",
                     desc="Generated test cells for forge playtest. Test profile only; never install for play.")
    class_fid = _clas(w)
    # kit bases
    for key, k in KIT.items():
        if key == "door":
            r = w.record("DOOR", k["edid"])
            r.add("FULL", zs("Door"))
            r.add("MODL", zs(kit_mesh(key)))
            r.add("MODB", f32(_bounds_radius(key)))
            r.add("DATA", u8(0))
        elif key == "trinket":
            r = w.record("MISC", k["edid"])
            r.add("FULL", zs("Test Trinket"))
            r.add("MODL", zs(kit_mesh(key)))
            r.add("MODB", f32(_bounds_radius(key)))
            r.add("DATA", struct.pack("<if", 5, 0.5))
        else:
            r = w.record("STAT", k["edid"])
            r.add("MODL", zs(kit_mesh(key)))
            r.add("MODB", f32(_bounds_radius(key)))
    # cells first (so refs get FormIDs before packages resolve them)
    cell_objs = {}
    for key, c in lay["cells"].items():
        cell = w.cell(c["edid"])
        cell.rec.add("FULL", zs(c["name"]))
        cell.rec.add("DATA", u8(0x01 | (0x80 if c["exterior"] else 0)))
        if not c["exterior"]:
            cell.rec.add("XCLL", _xcll())
        cell_objs[key] = cell
    # persistent / named refs get FormIDs before the NPC and package records point at them
    ref_recs = {}
    for key, c in lay["cells"].items():
        for i, ref in enumerate(c["refs"]):
            sig = "ACHR" if ref["base"].startswith("npc:") else "REFR"
            r = w.ref(cell_objs[key], sig, ref.get("edid"), ref.get("persistent", False))
            ref_recs[(key, i)] = r
            ref["formid"] = f"{r.fid:08X}"
    pkg_fids = {}

    def ref_fid(name: str) -> int:
        return w.fid(name)

    for edid, p in lay["packages"].items():
        pkg_fids[edid] = _package(w, edid, p, ref_fid)
        p["formid"] = f"{pkg_fids[edid]:08X}"

    def form_fid(name: str) -> int:
        return GOLD001 if name == "Gold001" else w.fid(name)

    for edid, d in lay["npcs"].items():
        _npc(w, edid, d, class_fid, pkg_fids, form_fid)
        d["formid"] = f"{w.fid(edid):08X}"
    # fill in the refs
    for key, c in lay["cells"].items():
        for i, ref in enumerate(c["refs"]):
            r = ref_recs[(key, i)]
            base = ref["base"]
            if base.startswith("npc:"):
                base_fid = w.fid(base[4:])
            elif base == "marker":
                base_fid = XMARKER_HEADING
            else:
                base_fid = w.fid(KIT[base]["edid"])
            r.add("NAME", u32(base_fid))
            if ref.get("teleport"):
                t = ref["teleport"]
                r.add("XTEL", struct.pack("<I6f", w.fid(t["to"]), *t["pos"], 0.0, 0.0, t["rot"]))
            x, y, z = ref["pos"]
            r.add("DATA", pos(x, y, z, 0.0, 0.0, ref["rot"]))
    for key, k in KIT.items():
        lay["kit"][key]["formid"] = f"{w.fid(k['edid']):08X}"
    for key, c in lay["cells"].items():
        c["formid"] = f"{w.fid(c['edid']):08X}"
    return w.build(), lay


def write(out_dir: Path) -> tuple[Path, Path]:
    """Write ForgeTestCells.esp + ForgeTestCells.layout.json into out_dir."""
    data, lay = build_plugin()
    out_dir.mkdir(parents=True, exist_ok=True)
    esp = out_dir / PLUGIN_NAME
    esp.write_bytes(data)
    lj = out_dir / "ForgeTestCells.layout.json"
    lj.write_text(json.dumps(lay, indent=1, sort_keys=True), encoding="utf-8")
    return esp, lj


def cell_key(name: str | None) -> str:
    """Map a test_plan cell name (arena/street/open or the cell EditorID) to a key."""
    if not name:
        return DEFAULT_CELL
    n = str(name).strip().lower()
    for key, c in CELLS.items():
        if n in (key, c["edid"].lower()):
            return key
    aliases = {"combat": "arena", "spells": "arena", "town": "street", "city": "street", "merchant": "street",
               "doors": "street", "exterior": "open", "weather": "open", "projectiles": "open"}
    if n in aliases:
        return aliases[n]
    raise ValueError(f"unknown test cell {name!r}; use one of {sorted(CELLS)}")


# ---------------------------------------------------------------- mesh kit (assetkit)
def build_kit(out_data: Path) -> list[Path]:
    """Generate the kit NIFs + textures under out_data (a Data-shaped folder). Needs numpy + Pillow."""
    from assetkit import mesh as M, nif as N, nifbuild as NB, texture as T

    files = []
    mats = {"stone": ("stone", "#8d8a83", 7), "wood": ("wood", "#7a5a3a", 11)}
    for name, (kind, color, seed) in mats.items():
        try:
            layer = T.material(kind, (256, 256), color, seed)
        except (KeyError, ValueError):
            layer = T.material("stone", (256, 256), color, seed)
        base = out_data / "textures" / KIT_TEX_DIR.replace("\\", "/") / name
        T.save_textures(layer, base, preview_png=False)
        files += [base.with_suffix(".dds"), base.parent / (base.name + "_n.dds")]
    for key, k in KIT.items():
        sx, sy, sz = k["size"]
        m = M.box(sx, sy, sz, name=key)
        m.translate(0, 0, -sz / 2 if k["origin"] == "top" else sz / 2)
        m.uv = m.uv * max(1.0, max(sx, sy, sz) / 256.0)       # tile the 256 px texture every 256 units
        tex = f"textures\\{KIT_TEX_DIR}\\{k['texture']}.dds"
        nif = NB.build(m, tex, name=k["edid"], profile="clutter" if key == "trinket" else "static",
                       prn=None, mass=0.5, havok_material="stone" if k["texture"] == "stone" else "wood",
                       glossiness=10.0)
        p = out_data / "meshes" / KIT_MESH_DIR.replace("\\", "/") / f"{key}.nif"
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(N.write(nif))
        files.append(p)
    return files
