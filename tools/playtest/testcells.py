"""ForgeTestCells.esp: three small generated test cells for quick-boot playtests.

  arena   ForgeTestArena  interior, lit, walled 2048 x 2048: spells and combat. An essential
          target dummy (ForgeArenaDummyRef) that never fights back, a passive spell caster
          (ForgeArenaCasterRef: scripted `cast` steps use it), cover blocks, a spawn marker.
  street  ForgeTestStreet behaves like an exterior (sky, weather, day/night): two rows of walls,
          a merchant with a work/evening schedule, two townsfolk, and a load door to the arena.
  open    ForgeTestOpen   behaves like an exterior, 4096 x 4096 open floor: weather and
          projectiles. A dummy at 1500 units and cover blocks at several ranges.

Everything is new records (no vanilla record is overridden). Vanilla references are limited to
engine-fixed FormIDs: Oblivion.esm's Imperial race (0x00000907), Gold001 (0x0000000F) and the
XMarkerHeading static (0x00000034). The geometry is a small mesh kit generated by assetkit
(meshes\\forge\\testcells\\*.nif), staged into the test game only for the run.

"Exterior" cells are interiors flagged "behave like exterior": Oblivion shows sky and weather in
them and `fw <weather>` works, without a worldspace, landscape or LOD. A real worldspace patch is
a Track G job.

A layout (cells, refs, NPC packages and schedules, kit sizes) is returned with the bytes and
saved next to the plugin as ForgeTestCells.layout.json; `forge preview` and the manifest use it.
"""

