# ---------------------------------------------------------------- layout (pure data)
def _floor(cx: float, cy: float, nx: int, ny: int) -> list[dict]:
    tiles = []
    for i in range(nx):
        for j in range(ny):
            x = cx + (i - (nx - 1) / 2) * 1024
            y = cy + (j - (ny - 1) / 2) * 1024
            tiles.append({"base": "floor", "pos": [x, y, 0.0], "rot": 0.0})
    return tiles


def _walls(hx: float, hy: float, gaps: tuple = ()) -> list[dict]:
    """Walls around a rectangle (half sizes hx, hy); gaps = list of (side, centre) to leave open."""
    out = []
    for side in ("n", "s", "e", "w"):
        length = 2 * (hx if side in "ns" else hy)
        for k in range(int(length // 1024)):
            c = -length / 2 + 512 + k * 1024
            if (side, c) in gaps:
                continue
            if side == "n":
                out.append({"base": "wall", "pos": [c, hy, 0.0], "rot": 0.0})
            elif side == "s":
                out.append({"base": "wall", "pos": [c, -hy, 0.0], "rot": 0.0})
            elif side == "e":
                out.append({"base": "wall", "pos": [hx, c, 0.0], "rot": math.pi / 2})
            else:
                out.append({"base": "wall", "pos": [-hx, c, 0.0], "rot": math.pi / 2})
    return out


